// tools/journal_clean.mjs — чистка текстов журналов-справочников (data/*.json → компендии JournalEntry).
// Запуск: node tools/journal_clean.mjs [--dry]   (повторный запуск ничего не меняет)
//
// Что делает:
//  · «<p><strong>Источник:</strong> …</p>» → сноска <p class="r-src">: только ссылка на книгу, без «(EN)»;
//    заметки составителя из того же абзаца («не переписываю», «сюжет без механики», «в файле 02»…) — убираются,
//    полезные оговорки («все правила необязательные») — отдельным абзацем, «Термины: a = b» — строкой <p class="r-terms">;
//  · ссылки на «файлы» черновика («см. файл `02`», «в файлах 08–10») — на главы журнала по названию;
//  · пустые абзацы.
// Правит JSON как текст: формат файлов (отступы, порядок ключей) не меняется.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DRY = process.argv.includes("--dry");
const FILES = ["rules", "rules-ghouls", "rules-infernal", "rules-homerules", "werewolf-books", "werewolf-rules", "mage-books", "wraith-books", "changeling-books", "demon-rules"];

// заметки составителя: что пропущено, где лежало в черновике, как пересказано
const META = /переписыва|переписан|не пересказ|пересказ (?:механики|своими)|пересказ\.?$|^Пересказ|опущен|пропущен|механик[иа]? (?:почти )?не содерж|без механики|сюжетн|сюжет и NPC|сюжет, механики|NPC не|Статистика NPC|уникальное(?: из блоков NPC)? —|файл|^Здесь (?:—|только|собраны)|здесь только|Страницы —|Остальное в книге|В остальных частях|^Остальное —|Большая часть объёма|^Блок \d|Книга в основном описательная/i;
const ABBR = /(?:^|[\s(])(?:гл|стр|с|см|т|д|п|ок|ед|им|англ|рус|пер|изд|Ed|No|vol|pp?|[A-ZА-ЯЁ])$/;

/** Абзац на предложения: точка + пробел + заглавная/«/(, не внутри скобок и не после сокращения или инициала. */
function sentences(text) {
  const out = []; let depth = 0, start = 0;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (c === "(" || c === "«") depth++;
    else if ((c === ")" || c === "»") && depth) depth--;
    else if (c === "." && !depth && /\s/.test(text[i + 1] ?? "") && /[А-ЯЁA-Z«(<]/.test(text.slice(i + 1).trimStart()[0] ?? "")) {
      if (ABBR.test(text.slice(Math.max(0, i - 8), i))) continue;
      out.push(text.slice(start, i + 1).trim()); start = i + 1;
    }
  }
  if (text.slice(start).trim()) out.push(text.slice(start).trim());
  return out;
}

const terms = s => s.replace(/^Термины:\s*/, "").replace(/ = /g, " — ");
const Q = '\\"';   // кавычка внутри строки JSON

function cleanSource(body) {
  const parts = sentences(body.replace(/\s*\((?:EN|рус\. пер\.)\)/g, ""));
  const cite = parts.shift() ?? "";
  const keep = [], glossary = [];
  for (const s of parts) {
    // «… Термины: a = b; c = d» — словарик может начинаться посреди предложения
    const ti = s.indexOf("Термины:");
    const head = ti > 0 ? s.slice(0, ti).trim() : ti === 0 ? "" : s;
    if (ti >= 0) glossary.push(terms(s.slice(ti)));
    if (head && !META.test(head)) keep.push(head);
  }
  return `<p class=${Q}r-src${Q}>Источник: ${cite}</p>`
    + (keep.length ? `<p>${keep.join(" ")}</p>` : "")
    + (glossary.length ? `<p class=${Q}r-terms${Q}><b>Термины:</b> ${glossary.join("; ")}</p>` : "");
}

// ссылки на файлы и строки черновика → главы журналов
const FILE_REFS = [
  [/ Подробно — файл по Гламуру\/Эпифании\./g, " Подробно — в главе «Темперы, Воля, Гламур, Эпифании, Клятвы»."],
  [/ Эти описания — в файлах 08–10\./g, " Эти описания — в главах «Искусства: …»."],
  [/ Подробнее — файл по гл\. 7\./g, " Подробнее — в главе «Кантрипы, обряды-условия (bunks) и Высвобождение»."],
  [/ Домены Ночи, Рассвета и Сумерек — файлы `03`, `04`\. В этом файле «Д» = Домен Дня \(Day\)\./g, " Домены Ночи, Рассвета и Сумерек — в своих главах. Здесь «Д» — Домен Дня (Day)."],
  [/ — в файле `02`\./g, " — в главе «Домены: правила кантрипов и Высвобождения, общие кантрипы, Домен Дня»."],
  [/; см\. `02`\)/g, "; см. главу «Домены»)"],
  [/Прописаны по группам в файле `06`\./g, "Прописаны по группам в главе «Традиции, Конвенции Технократии, Ремёсла (Disparates), Мародёры»."],
  [/ Механика создания — см\. файл `04`\./g, " Механика создания — в главе «Павшие Фера и „ложные породы“»."],
  [/ Характеристики конкретных Пород — в файлах 01–11\./g, " Характеристики каждой Породы — в её главе."],
  [/ См\. файл «Достоинства и недостатки»\./g, " См. компендий «Достоинства и недостатки»."],
  [/ — см\. файлы Changing Breeds\./g, " — в книге «Меняющие облик (Фера)»."],
  [/; см\. файл о Психее\./g, "; см. главу о Психее."],
  [/ Обряды — см\. файл о гулях и обрядах\./g, " Обряды — в главе «7. Гули, ревенанты и обряды Шабаша»."],
  // номера строк текстового черновика: «(строки 10895–11333)», «(строки 11333–11590, с. 285–293 …»
  [/ ?\(строки \d+–\d+\)/g, ""], [/строки \d+–\d+, /g, ""],
  [/ — `Wraith20_Book_of_Oblivion\/01`\./g, " — в «Книге Забвения», глава 1."],
  [/в справочнике — M20_Sorcerer/g, "в справочнике — книга «Колдун»"],
  // «(кратко)» в названиях глав и подписях: краткость читателю не новость
  [/ \(кратко(?:[;,][^)"]*)?\)/g, ""], [/\(кратко, (стр\.[^)"]*)\)/g, "($1)"],
  [/ \(сводка своими словами\)/g, ""], [/<p>Своими словами\.<\/p>/g, ""], [/основной книге своими словами\./g, "основной книге."], [/ — своими словами:/g, ":"]
];

// фразы составителя о самом пересказе и о скане — предложение целиком (в пределах одного абзаца, без тегов внутри)
const VOICE = /[^.<>«»]*(?:в английском скане|пересказ собран|не дословн|пересказ основной процедуры|[Пп]ересказ своими словами|пересказывают правила своими словами|кратким пересказом|Для своей системы следует|здесь не переписаны|в (?:этом )?справочнике (?:опущены|не расписаны)|Ниже — краткий пересказ)[^.<>]*(?:\.\s?|(?=<))/g;

let total = 0;
for (const f of FILES) {
  const file = path.join(ROOT, "data", `${f}.json`);
  const src = fs.readFileSync(file, "utf8");
  let s = src, n = 0;
  s = s.replace(/<p>\s*<(strong|b)>\s*Источник:?\s*<\/\1>\s*([\s\S]*?)<\/p>/g, (m, _t, body) => { n++; return cleanSource(body.trim()); });
  for (const [re, to] of FILE_REFS) s = s.replace(re, () => { n++; return to; });
  s = s.replace(VOICE, () => { n++; return ""; });
  s = s.replace(/\(\s*\)|<(p|li|em)>\s*<\/\1>/g, () => { n++; return ""; });
  if (s !== src) { JSON.parse(s); if (!DRY) fs.writeFileSync(file, s); }
  if (n) console.log(`${f}: ${n}`);
  total += n;
}
console.log(DRY ? `(проверка) правок: ${total}` : `правок: ${total}`);
