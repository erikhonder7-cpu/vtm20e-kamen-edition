def extend_disciplines(disc):
    """Путь биотауматургии — в пути Тауматургии; силы старейшин — в свои Дисциплины (гл. 3). Повторно не добавляет."""
    th = disc.get("thaumaturgy")
    if th is not None and not any(p.get("en") == BIOTHAUMATURGY["en"] for p in th.get("paths", [])):
        b = BIOTHAUMATURGY
        th.setdefault("paths", []).append({"name": b["name"], "en": b["en"], "era": "", "source": SRC, "fan": True,
            "html": f"<p>{b['text']}</p>",
            "powers": [{"level": lv, "name": n, "en": en, "source": SRC, "roll": {"trait1": "willpower.permanent", "difficulty": lv + 3},
                        "html": _card(d, s)} for lv, n, en, d, s in b["powers"]]})
    n = 0
    for key, lv, name, en, d, s, roll in ELDER_POWERS:
        tgt = disc.get(key)
        if tgt is None or any(p.get("en") == en for p in tgt.get("powers", [])):
            continue
        tgt.setdefault("powers", []).append({"level": lv, "name": name, "en": en, "source": SRC, "fan": True, "roll": roll, "html": _card(d, s)})
        n += 1
    return n


def collect_merits():
    """Черты дампиров из аудита партии 32 (Accursed Heirs) — только для дампиров (dhampir: true), не в общем списке."""
    import html
    src = json.load(open(os.path.join(HERE, "sources", "dhampir", "accursed_heirs_merits.json"), encoding="utf-8"))
    src = src if isinstance(src, list) else next(iter(src.values()))
    esc = lambda s: html.escape((s or "").strip(), quote=False)
    sec = lambda t: f'<h4 class="r-sec">{t}</h4>'
    out = []
    for x in src:
        out.append({"kind": x["kind"], "category": x["category"], "name": x["name"], "en": x.get("en", ""),
                    "cost": str(x.get("cost", "")), "min": x.get("min", 1), "max": x.get("max", 1), "clan": "", "sect": "",
                    "era": "", "source": SRC, "dhampir": True, "fan": True,
                    "html": f'{sec("Описание")}<p>{esc(x.get("description_text"))}</p>{sec("Система")}<p>{esc(x.get("system_text"))}</p>'})
    return out


def build():
    def right(b, rare):
        req = b.get("req", "")
        levels = [{"level": i + 1, "name": n, "en": en, "roll": roll, "cost": cost, "text": text}
                  for i, (n, en, roll, cost, text) in enumerate(b["levels"])]
        return {"key": b["key"], "name": b["name"], "en": b["en"], "req": req, "rare": rare, "scaling": bool(b.get("scaling")),
                "text": b["text"], "levels": levels}
    rights = [right(b, False) for b in BLOODRIGHTS] + [right(b, True) for b in RARE]
    rituals = [{"key": f"dririmancy|{n}", "level": lv, "name": n, "en": en, "text": t,
                "roll": R(A("wits"), B("occult"), 5 + lv)} for lv, n, en, t in RITUALS]
    clans = {k: {"nick": v[0], "rights": v[1], "weakness": v[2]} for k, v in CLANS.items()}
    for b in BACKGROUNDS:
        b.update({"dhampir": True, "source": SRC, "min": 1, "max": 5})
    data = {"source": SRC, "concepts": CONCEPTS, "bloodrights": rights, "rituals": rituals, "clans": clans,
            "backgrounds": BACKGROUNDS, "merits": collect_merits(), "creation": CREATION, "rules": RULES}
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    return {"concepts": len(CONCEPTS), "bloodrights": len(rights), "powers": sum(len(r["levels"]) for r in rights),
            "rituals": len(rituals), "merits": len(data["merits"])}


